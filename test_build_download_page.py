"""Tests for build_download_page.py. Standard library only: this repo has no
dependencies and no build step.

    python3 -m unittest -v
"""
import contextlib
import io
import os
import re
import tempfile
import unittest

import build_download_page as page

PROD = [
    "Tchat.N.Sign_0.5.1_aarch64.dmg",
    "Tchat.N.Sign_0.5.1_x64-setup.exe",
    "Tchat.N.Sign_0.5.1_x64_en-US.msi",
    "Tchat.N.Sign_0.5.1_amd64.deb",
    "Tchat.N.Sign-0.5.1-1.x86_64.rpm",
    # updater artifacts ride the release too, but are not download buttons
    "Tchat.N.Sign_aarch64.app.tar.gz",
    "Tchat.N.Sign_0.5.1_amd64.deb.sig",
]
DEV = [
    "Tchat.N.Sign.Dev_0.6.0_aarch64.dmg",
    "Tchat.N.Sign.Dev_0.6.0_amd64.deb",
    "Tchat.N.Sign.Dev_0.6.0_x64-setup.exe",
]
RELEASE = f"https://github.com/{page.REPO}/releases/download"


class PageTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def installers(self, names):
        """A releases dir whose desktop/ holds `names` (1 kB each: only sizes are read)."""
        root = os.path.join(self.tmp.name, "releases")
        os.makedirs(os.path.join(root, "desktop"), exist_ok=True)
        for name in names:
            with open(os.path.join(root, "desktop", name), "wb") as f:
                f.write(b"\0" * 1000)
        return root

    def build(self, version, names, *flags, out="index.html"):
        out_path = os.path.join(self.tmp.name, out)
        with contextlib.redirect_stdout(io.StringIO()):
            page.main([version, self.installers(names), out_path, *flags])
        with open(out_path, encoding="utf-8") as f:
            return f.read()

    def refused(self, *argv):
        err = io.StringIO()
        with contextlib.redirect_stderr(err), self.assertRaises(SystemExit) as raised:
            page.main(list(argv))
        self.assertNotEqual(raised.exception.code, 0)
        return err.getvalue() + str(raised.exception.code)


class ProdPage(PageTest):
    def test_without_options_it_is_the_page_as_it_was_before_channels(self):
        out = self.build("0.5.1", PROD)
        self.assertIn("<title>Tchat N Sign — Application de bureau</title>", out)
        self.assertIn("Tchat N Sign pour ordinateur", out)
        self.assertIn('href="releases/desktop/Tchat.N.Sign_0.5.1_aarch64.dmg"', out)
        self.assertIn('class="shots"', out)
        self.assertNotIn("noindex", out)
        self.assertNotIn("devnote", out)
        self.assertIn("Version 0.5.1", out)

    def test_without_options_it_is_byte_for_byte_the_page_generated_before_channels(self):
        # fixtures/index.prod-0.5.1.html was generated by the script as it was BEFORE
        # channels (commit 2db19a7), from these file names at 3 MB each. A few
        # assertNotIn would let a stray space through; this does not.
        root = os.path.join(self.tmp.name, "releases")
        os.makedirs(os.path.join(root, "desktop"))
        for name in PROD:
            with open(os.path.join(root, "desktop", name), "wb") as f:
                f.truncate(3_000_000)
        out_path = os.path.join(self.tmp.name, "index.html")
        with contextlib.redirect_stdout(io.StringIO()):
            page.main(["0.5.1", root, out_path])
        golden = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "index.prod-0.5.1.html")
        with open(out_path, "rb") as built, open(golden, "rb") as expected:
            self.assertEqual(built.read(), expected.read())

    def test_buttons_follow_the_os_groups_and_skip_updater_artifacts(self):
        out = self.build("0.5.1", PROD)
        for ext in (".dmg", ".exe", ".msi", ".deb", ".rpm"):
            self.assertRegex(out, rf'href="[^"]*{re.escape(ext)}"')
        self.assertNotIn("app.tar.gz", out)
        self.assertNotIn(".sig", out)

    def test_it_shows_the_size_of_each_installer(self):
        self.assertIn('<span class="sz">0 Mo</span>', self.build("0.5.1", PROD))

    def test_with_a_tag_the_buttons_point_at_that_release_not_at_the_tree(self):
        out = self.build("0.5.1", PROD, "--tag", "v0.5.1")
        self.assertIn(f'href="{RELEASE}/v0.5.1/Tchat.N.Sign_0.5.1_aarch64.dmg"', out)
        self.assertNotIn("releases/desktop/", out)

    def test_a_file_name_is_url_quoted_in_the_link_and_escaped_in_the_label(self):
        out = self.build("1.0.0", ["Tchat N&Sign_1.0.0_amd64.deb"], "--tag", "v1.0.0")
        self.assertIn(f'href="{RELEASE}/v1.0.0/Tchat%20N%26Sign_1.0.0_amd64.deb"', out)


class DevPage(PageTest):
    def setUp(self):
        super().setUp()
        self.out = self.build("0.6.0", DEV, "--channel", "dev", "--tag", "dev-v0.6.0")

    def test_it_says_what_it_is(self):
        self.assertIn("<title>Tchat N Sign Dev — Build de développement</title>", self.out)
        self.assertIn("<h1>Tchat N Sign Dev pour ordinateur</h1>", self.out)
        self.assertIn('class="devnote"', self.out)
        self.assertIn("Version 0.6.0", self.out)
        self.assertNotIn("Application de bureau", self.out)

    def test_it_links_back_to_the_page_customers_use(self):
        self.assertIn('<a href="../">la page principale</a>', self.out)

    def test_the_repo_is_public_so_it_asks_search_engines_to_stay_away(self):
        self.assertIn('<meta name="robots" content="noindex, nofollow" />', self.out)

    def test_it_has_no_marketing_screenshots(self):
        self.assertNotIn('class="shots"', self.out)
        self.assertNotIn("screenshots/", self.out)

    def test_its_buttons_point_at_the_dev_release(self):
        self.assertIn(f'href="{RELEASE}/dev-v0.6.0/Tchat.N.Sign.Dev_0.6.0_aarch64.dmg"', self.out)
        self.assertNotIn(f"{RELEASE}/v0.6.0/", self.out)

    def test_it_is_written_into_a_folder_that_does_not_exist_yet(self):
        self.build("0.6.0", DEV, "--channel", "dev", "--tag", "dev-v0.6.0", out="site/dev/index.html")
        self.assertTrue(os.path.isfile(os.path.join(self.tmp.name, "site", "dev", "index.html")))


class Placeholders(PageTest):
    def test_no_placeholder_survives_in_either_channel(self):
        for channel, version, names, tag in (
            ("prod", "0.5.1", PROD, "v0.5.1"),
            ("dev", "0.6.0", DEV, "dev-v0.6.0"),
        ):
            with self.subTest(channel=channel):
                out = self.build(version, names, "--channel", channel, "--tag", tag)
                self.assertEqual(re.findall(r"__[A-Z0-9_]+__", out), [])

    def test_every_channel_fills_the_same_placeholders(self):
        self.assertEqual(set(page.CHANNELS["prod"]), set(page.CHANNELS["dev"]))
        for key in page.CHANNELS["prod"]:
            self.assertIn(f"__{key.upper()}__", page.PAGE)


class Refusals(PageTest):
    def existing_page(self):
        """A page already published at the output path, which a refusal must leave alone."""
        out = os.path.join(self.tmp.name, "published.html")
        with open(out, "w", encoding="utf-8") as f:
            f.write("EXISTING PAGE")
        return out

    def assertUntouched(self, out):
        with open(out, encoding="utf-8") as f:
            self.assertEqual(f.read(), "EXISTING PAGE")

    # Without a tag the buttons link to releases/desktop/ in the tree. For dev that is
    # wrong either way: from /dev/index.html it is a folder that does not exist, and at
    # the root it is PROD's installers under a banner that says "dev".
    def test_a_dev_page_needs_a_release_tag_and_leaves_a_published_page_alone(self):
        root, out = self.installers(DEV), self.existing_page()
        message = self.refused("0.6.0", root, out, "--channel", "dev")
        self.assertIn("--tag", message)
        self.assertIn("dev-v0.6.0", message)
        self.assertUntouched(out)

    def test_an_empty_tag_is_refused_whatever_the_channel_and_leaves_the_page_alone(self):
        root, out = self.installers(DEV), self.existing_page()
        for channel in ("dev", "prod"):
            with self.subTest(channel=channel):
                message = self.refused("0.6.0", root, out, "--channel", channel, "--tag", "")
                self.assertIn("--tag", message)
                self.assertUntouched(out)

    def test_prod_without_a_tag_is_still_the_historical_mode(self):
        out = self.build("0.5.1", PROD)
        self.assertIn('href="releases/desktop/Tchat.N.Sign_0.5.1_aarch64.dmg"', out)

    def test_a_dev_page_will_not_link_a_prod_tag_nor_the_reverse(self):
        root = self.installers(DEV)
        out = os.path.join(self.tmp.name, "x.html")
        self.assertIn("dev-v0.6.0", self.refused("0.6.0", root, out, "--channel", "dev", "--tag", "v0.6.0"))
        self.assertIn("v0.6.0", self.refused("0.6.0", root, out, "--channel", "prod", "--tag", "dev-v0.6.0"))

    def test_a_tag_of_another_version_would_label_the_page_with_the_wrong_release(self):
        root = self.installers(DEV)
        out = os.path.join(self.tmp.name, "x.html")
        self.assertIn("dev-v0.6.1", self.refused("0.6.1", root, out, "--channel", "dev", "--tag", "dev-v0.6.0"))

    def test_an_unknown_channel_is_refused(self):
        root = self.installers(DEV)
        self.assertIn("staging", self.refused("0.6.0", root, "x.html", "--channel", "staging"))

    def test_a_page_with_no_installers_never_replaces_a_working_one(self):
        out = os.path.join(self.tmp.name, "x.html")
        self.assertIn("no installers found", self.refused("0.6.0", self.installers([]), out))
        self.assertFalse(os.path.exists(out))

    def test_a_missing_desktop_dir_is_the_same_failure(self):
        out = os.path.join(self.tmp.name, "x.html")
        self.assertIn("no installers found", self.refused("0.6.0", os.path.join(self.tmp.name, "nope"), out))


if __name__ == "__main__":
    unittest.main()
